def _grass_tile(rng: Rng) -> Canvas:
    g = Canvas(CELL, CELL, fill="moss")
    for _ in range(5):
        g.set(rng.randint(0, 15), rng.randint(0, 15), "moss_dark")
    for _ in range(3):
        g.set(rng.randint(0, 15), rng.randint(0, 15), "moss_light")
    return g


def on_grass_preview(sheet: Sheet, path: str, scale: int = 4) -> str:
    rng = Rng("nature-grass-preview")
    cols = 16  # cells per row
    # lay props on a cell grid, leaving one empty cell between them
    placements: List[Tuple[str, int, int]] = []
    x = y = 0
    row_h = 0
    for name, _b, (cw, ch), _s, _o, _t in INVENTORY:
        if x + cw > cols:
            x = 0
            y += row_h + 1
            row_h = 0
        placements.append((name, x, y))
        x += cw + 1
        row_h = max(row_h, ch)
    rows = y + row_h + 1
    world = Canvas(cols * CELL, rows * CELL)
    for cy in range(rows):
        for cx in range(cols):
            world.blit(_grass_tile(rng), cx * CELL, cy * CELL)
    for name, cx, cy in placements:
        e = sheet.get(name)
        world.blit(e.canvas, cx * CELL, cy * CELL)
    big = world.scaled(scale)
    title = Canvas(big.w, 14, fill=(20, 21, 28))
    title.stamp("NATURE PROPS ON GRASS (moss) - review only", 4, 2, (255, 214, 120), scale=2)
    out = Canvas(big.w, big.h + title.h, fill=(20, 21, 28))
    out.blit(title, 0, 0)
    out.blit(big, 0, title.h)
    return out.save(path)


def build(art_root: str, preview_dir: str, cellmap_dir: str) -> List[str]:
    sheet = make_sheet()
    tiles_dir = os.path.join(art_root, "Tiles")
    png, js = sheet.save(tiles_dir)
    written = [png, js]
    written.append(sheet.preview(os.path.join(preview_dir, f"{sheet.file_name}_preview.png"),
                                 scale=4, labels=True))
    written.append(on_grass_preview(sheet, os.path.join(preview_dir, f"{sheet.file_name}_on_grass_preview.png")))
    cm_png, cm_md = sheet.cellmap(os.path.join(cellmap_dir, f"{sheet.name}_cellmap.png"),
                                  os.path.join(cellmap_dir, f"{sheet.name}.md"))
    written += [cm_png, cm_md]
    return written


