def _check_ring(name: str, c: Canvas) -> None:
    """Every opaque pixel on the canvas border must be ink_black (an outline that was clipped
    by the edge means the art touched the edge of its cell footprint)."""
    bad = []
    for x in range(c.w):
        for y in (0, c.h - 1):
            n = c.get_name(x, y)
            if n is not None and n != "ink_black":
                bad.append((x, y, n))
    for y in range(c.h):
        for x in (0, c.w - 1):
            n = c.get_name(x, y)
            if n is not None and n != "ink_black":
                bad.append((x, y, n))
    if bad:
        raise ValueError(f"{name}: art touches the sprite edge (outline clipped) at {bad[:6]}")


