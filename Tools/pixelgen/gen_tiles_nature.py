def _waterfall_frames() -> List[Canvas]:
    rock = pat(_WF_ROCK, 16, 32)
    water = Canvas.from_pattern([r for r in _WF_WATER.strip("\n").split("\n")], CM)
    frames = []
    for f in range(2):
        c = rock.copy()
        # water pours over the ledge (row 3) and falls in the opening below it
        c.paste_pattern(["cWccWccWcc"], 3, 3, CM)
        c.blit(water.shifted(0, 2 * f, wrap=True), 3, 4)
        foam = Canvas.from_pattern([r for r in _WF_FOAM[f].strip("\n").split("\n")], CM)
        c.blit(foam, 3, 27)
        # basin between the foot rocks
        c.paste_pattern(["WcWWcWW" if f == 0 else "cWWcWWc"], 5, 30, CM)
        frames.append(c)
    return frames


